// Register individually generated frames and pack nonoverlapping atlas windows.
// Sources remain untouched; register, clear the requested live-fill window and pack.
import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {resolve} from 'node:path';
import assert from 'node:assert/strict';
import {chromium} from 'playwright';
const root=resolve(import.meta.dirname,'..'),dir=resolve(root,'assets/raids/ui-kit-v1');
const keys=['ashmaw','thessaly','morwenna','grimjaw','skarth'];
const sources=await Promise.all(keys.map(async key=>({key,src:'data:image/png;base64,'+(await readFile(resolve(dir,`boss-portraits/${key}-final.png`))).toString('base64')})));
const browser=await chromium.launch({headless:true});
try{
 const page=await browser.newPage();
 const result=await page.evaluate(async sources=>{
  const load=src=>new Promise((resolve,reject)=>{const img=new Image();img.onload=()=>resolve(img);img.onerror=reject;img.src=src;});
  const width=1216,height=406,atlas=document.createElement('canvas');atlas.width=1280;atlas.height=2222;const ac=atlas.getContext('2d');const entries=[];
  // Preserve each full source, including all organic curls and ice spikes.
  // A one-pixel generation width variation is normalized to the common canvas.
  const channel={x:280,y:168,width:804,height:68};
  for(const [i,s] of sources.entries()){
   const source=await load(s.src);if(Math.abs(source.naturalWidth-2172)>2||source.naturalHeight!==724)throw new Error(`${s.key}: unexpected source canvas`);
   const c=document.createElement('canvas');c.width=width;c.height=height;const ctx=c.getContext('2d');ctx.imageSmoothingQuality='high';ctx.drawImage(source,0,0,width,height);
   // ImageGen removes the whole inner panel; normalize any residual mist or
   // alpha matte in the exact live-fill rectangle to true zero-alpha pixels.
   ctx.clearRect(channel.x,channel.y,channel.width,channel.height);
   const x=32,y=32+i*438;ac.drawImage(c,x,y);entries.push({key:s.key,name:`boss-health-${s.key}`,x,y,width,height,logicalWidth:width/2,logicalHeight:height/2,source:{file:`boss-portraits/${s.key}-final.png`,width:source.naturalWidth,height:source.naturalHeight},channel,png:c.toDataURL().split(',')[1]});
  }
  return {width:atlas.width,height:atlas.height,entries,png:atlas.toDataURL().split(',')[1]};
 },sources);
 for(const [i,a] of result.entries.entries()){
  assert(a.x>=32&&a.y>=32&&a.x+a.width<=result.width-32&&a.y+a.height<=result.height-32,`${a.key}: out of bounds`);
  for(const b of result.entries.slice(i+1))assert(a.x+a.width+32<=b.x||b.x+b.width+32<=a.x||a.y+a.height+32<=b.y||b.y+b.height+32<=a.y,`${a.key} overlaps ${b.key}`);
 }
 await mkdir(resolve(dir,'sprites'),{recursive:true});
 for(const e of result.entries)await writeFile(resolve(dir,'sprites',`${e.name}.png`),Buffer.from(e.png,'base64'));
 await writeFile(resolve(dir,'boss-health-atlas.png'),Buffer.from(result.png,'base64'));
 const index={version:2,atlas:'boss-health-atlas.png',width:result.width,height:result.height,pixelRatio:2,gutter:32,entries:result.entries.map(({png,...entry})=>entry)};
 await writeFile(resolve(dir,'boss-health-index.json'),JSON.stringify(index,null,2)+'\n');
 const css=['/* Generated by build-tools/build-raid-boss-portraits.mjs. */','.raid-boss-art { display:block;aspect-ratio:1216/406;background-image:url("./boss-health-atlas.png");background-repeat:no-repeat; }'];
 for(const e of index.entries)css.push(`.raid-boss-art[data-encounter="${e.key}"] { background-size:${100*index.width/e.width}% ${100*index.height/e.height}%;background-position:${100*e.x/(index.width-e.width)}% ${100*e.y/(index.height-e.height)}%; }`);
 await writeFile(resolve(dir,'boss-health-atlas.css'),css.join('\n')+'\n');
 console.log('Packed five separately generated 1216x406 overlays into a 1280x2222 atlas with verified 32px gutters.');
}finally{await browser.close();}
