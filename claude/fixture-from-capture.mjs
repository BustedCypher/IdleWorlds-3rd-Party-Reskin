#!/usr/bin/env node
/**
 * Rebuild a live menu's markup from a capture-skills-quests.js JSON, as a
 * test fixture (tests/fixtures/live-2026-10-16/).
 *
 *   node claude/fixture-from-capture.mjs <capture.json> <out.html>
 *
 * The capture records each node's tag, classes, attributes and OWN text
 * (text nodes directly under it), in document order with a path. Own text is
 * emitted before the children, which is how every leaf-and-label node in the
 * Skills / Quests menus is built. Inline <style> blocks come from the
 * capture's full `inlineStyles`, not the node's truncated text. Hidden legacy
 * cards (`.iw-skill-cards-wrap`) are kept: the game ships them.
 *
 * Text was whitespace-collapsed and cut at 100 chars by the capture; that is
 * accepted (no menu label is that long).
 */

import { readFile, writeFile } from 'node:fs/promises';

const [, , src, out] = process.argv;
if (!src || !out) { console.error('usage: fixture-from-capture.mjs <capture.json> <out.html>'); process.exit(2); }
const cap = JSON.parse(await readFile(src, 'utf8'));

const esc = s => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const attr = s => String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;');
const VOID = new Set(['img', 'input', 'br', 'hr', 'path', 'circle', 'rect', 'line']);

function render(menu) {
  const nodes = menu.nodes;
  const styles = [...cap.inlineStyles];
  // children by parent path
  const kids = new Map();
  for (const n of nodes) {
    const parent = n.path.includes('>') ? n.path.slice(0, n.path.lastIndexOf('>')) : null;
    if (!kids.has(parent)) kids.set(parent, []);
    kids.get(parent).push(n);
  }
  const emit = n => {
    const a = Object.entries(n.attrs || {})
      // the capture cuts long values with "…(N)"; a cut path is dropped, not faked
      .filter(([k, v]) => !(k === 'd' && /…\(\d+\)$/.test(v)))
      .map(([k, v]) => ` ${k}="${attr(v)}"`).join('');
    const cls = n.cls ? ` class="${attr(n.cls)}"` : '';
    const style = n.inline ? ` style="${attr(n.inline)}"` : '';
    if (n.tag === 'style') return `<style>${styles.shift()?.css || ''}</style>`;
    const inner = (n.text ? esc(n.text) : '') + (kids.get(n.path) || []).map(emit).join('');
    return VOID.has(n.tag) ? `<${n.tag}${cls}${a}${style}/>` : `<${n.tag}${cls}${a}${style}>${inner}</${n.tag}>`;
  };
  return emit(nodes[0]);
}

const byHeading = h => cap.menus.find(m => m.heading === h);
const skills = byHeading('Skill Actions');
const quests = byHeading('Quests');
if (!skills || !quests) throw new Error('capture lacks the Skill Actions or Quests panel');

const html = `<!-- Generated by claude/fixture-from-capture.mjs from a live capture
     (${cap.meta.captured}, ${cap.meta.url}, data-skin=${cap.meta.dataSkin}). Do not hand-edit. -->
<div class="iw-fixture-col" id="col-skills">${render(skills)}</div>
<div class="iw-fixture-col" id="col-quests">${render(quests)}</div>
`;
await writeFile(out, html);
console.log(`wrote ${out} (${html.length} bytes)`);
