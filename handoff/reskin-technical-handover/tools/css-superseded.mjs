#!/usr/bin/env node
/**
 * css-superseded.mjs — list declarations that can never apply because a LATER
 * rule with the IDENTICAL selector (in the same @media/@container context)
 * sets the same property with equal or higher priority.
 *
 *   node handoff/reskin-technical-handover/tools/css-inventory.mjs   # first
 *   node handoff/reskin-technical-handover/tools/css-superseded.mjs
 *
 * Reads tools/css-inventory.json and writes tools/css-superseded.md.
 *
 * Cascade order is the runtime injection order: style element, then the
 * concatenation order inside it, then source line. Identical selector text
 * means identical specificity, so the later declaration wins unless the
 * earlier one is !important and the later one is not.
 *
 * This is a deliberately CONSERVATIVE lower bound of dead CSS:
 *  - a declaration counts only when EVERY selector in its rule's selector list
 *    is overridden (`a, b { color: red }` then `a { color: blue }` still
 *    colours `b`);
 *  - different selectors that override each other are not counted;
 *  - shorthand/longhand interactions (`background` vs `background-image`)
 *    are not counted;
 *  - inline styles written by the renderers are not considered.
 * It should never report a live declaration as dead, which is what makes the
 * list usable as a deletion worklist (still verify with the visual fixtures
 * and the cascade suites before deleting anything).
 */
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const inventory = JSON.parse(await readFile(path.join(HERE, 'css-inventory.json'), 'utf8'));

const FILE_ORDER = [
  'base.css', 'tooltip-engine.css', 'inventory.css',
  'skillpanel.css', 'skillcard-v2.css', 'skillcard-v2-runtime-safe.css', 'card-button-atlas.css', 'card-buttons.css',
  'header.css', 'overlay.css',
  'ui-system.css', 'compact-buttons.css', 'village-scene.css', 'collapsible.css',
];
const INACTIVE = new Set(['header.claude.css']);
const SEP = ' ␞ ';

const all = inventory.sheets.flatMap(s => s.rules);
const unknown = [...new Set(all.map(r => r.file))].filter(f => !FILE_ORDER.includes(f) && !INACTIVE.has(f));
if (unknown.length) throw new Error(`css-superseded: unaccounted stylesheet(s): ${unknown.join(', ')}`);
const rules = all.filter(r => FILE_ORDER.includes(r.file));
if (!rules.length) throw new Error('css-superseded: zero rules read - the inventory is broken, not clean');

rules.sort((a, b) => FILE_ORDER.indexOf(a.file) - FILE_ORDER.indexOf(b.file) || a.line - b.line);
const order = new Map(rules.map((r, i) => [r, i]));
const norm = s => s.replace(/\s+/g, ' ').trim();
const contextOf = r => (r.context || []).map(c => (typeof c === 'string' ? c : c.prelude || c.name || JSON.stringify(c))).join(' > ');

const groups = new Map();
for (const r of rules) {
  for (const s of r.selectors) {
    const key = contextOf(r) + SEP + norm(s.selector);
    if (!groups.has(key)) groups.set(key, []);
    groups.get(key).push(r);
  }
}

const rows = [];
for (const rule of rules) {
  const context = contextOf(rule);
  for (const d of rule.declarations || []) {
    const winners = [];
    for (const s of rule.selectors) {
      const list = groups.get(context + SEP + norm(s.selector)) || [];
      const winner = list.find(later => order.get(later) > order.get(rule) &&
        (later.declarations || []).some(e => e.prop === d.prop && (e.important || !d.important)));
      if (!winner) { winners.length = 0; break; }
      winners.push(winner);
    }
    if (winners.length && winners.length === rule.selectors.length) {
      rows.push({
        file: rule.file, line: d.line, prop: d.prop, important: d.important,
        winner: [...new Set(winners.map(w => `${w.file}:${w.line}`))].join(', '),
        selector: rule.selectors.map(s => norm(s.selector)).join(', '),
        context,
      });
    }
  }
}

const perFile = new Map();
for (const r of rows) perFile.set(r.file, (perFile.get(r.file) || 0) + 1);
const cell = s => s.replace(/\|/g, '\\|');

const md = [
  '# Superseded declarations (identical selector, later rule wins)',
  '',
  `Generated by \`tools/css-superseded.mjs\` from \`tools/css-inventory.json\` (commit \`${inventory.commit}\`). ` +
  'A conservative lower bound: see the script header for what is not counted. Each row is one declaration that never applies.',
  '',
  `**${rows.length}** superseded declarations (${rows.filter(r => r.important).length} of them \`!important\`).`,
  '',
  '| File | Superseded declarations |',
  '| --- | ---: |',
  ...[...perFile.entries()].sort((a, b) => b[1] - a[1]).map(([f, n]) => `| ${f} | ${n} |`),
  '',
  '| Declaration (file:line) | Property | Overridden by | Context | Selector |',
  '| --- | --- | --- | --- | --- |',
  ...rows.map(r => `| ${r.file}:${r.line} | \`${r.prop}\`${r.important ? ' `!important`' : ''} | ${r.winner} | ${r.context ? `\`${cell(r.context)}\`` : '—'} | \`${cell(r.selector)}\` |`),
  '',
];
await writeFile(path.join(HERE, 'css-superseded.md'), md.join('\n'));
console.log(`css-superseded: ${rows.length} superseded declarations (${rows.filter(r => r.important).length} !important) -> tools/css-superseded.md`);
